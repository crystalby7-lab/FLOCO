export type Track = 'basic' | 'adv'

export type Q =
  | { k: 'ox'; q: string; a: boolean; why: string }
  | { k: 'pick'; q: string; opts: string[]; a: number; why: string }
  | { k: 'order'; q: string; items: string[]; why: string }
  | { k: 'sort'; q: string; bins: [string, string]; items: [string, 0 | 1][]; why: string }
  | { k: 'num'; q: string; a: number; unit: string; why: string }
  | { k: 'write'; q: string; keys: string[]; sample: string; why: string }

export type LessonDef = {
  id: string
  title: string
  goal: string // 이 레슨에서 하는 것 (팀 문서 문장)
  core: string[] // 개념 카드
  case?: string // 적용(5레슨)·자료 읽기 레슨의 사례 자료
  qs: Q[]
  note: string // 내 노트에 남는 한 줄
}
export type ChapterDef = { id: string; no: number; title: string; lessons: LessonDef[] }

