export const COURSE: Record<Track, ChapterDef[]> = { basic: BASIC, adv: ADV }

export const chapterOf = (track: Track, i: number) => COURSE[track][i]
export const lessonById = (id: string) => {
  for (const track of ['basic', 'adv'] as Track[])
    for (const c of COURSE[track]) for (const l of c.lessons) if (l.id === id) return { track, c, l }
  return null
}
export const chapterDone = (c: ChapterDef, done: Record<string, unknown>) => c.lessons.every((l) => done[l.id])
