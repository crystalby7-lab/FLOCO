// Basic / Advanced (트랙)
// - 공통: 레슨 제목, 핵심 개념 카드(core), 공통 문제(t 없음), 내 노트에 남는 한 줄(note)
// - Basic만: 생활 속 쉬운 예시(basic), 개념 확인 문제(t: 'b') — 처음 배우는 학생
// - Advanced만: 더 깊이(adv) — 숫자 계산·실제 용어·적용, 심화 문제(t: 'a', 계산·서술형 많음) — 이미 조금 아는 학생
// 진도는 트랙과 상관없이 레슨 단위로 저장된다(중간에 트랙을 바꿔도 이어서 함).

export type Track = 'basic' | 'adv'

export type Q =
  | { k: 'ox'; q: string; a: boolean; why: string; t?: 'b' | 'a' }
  | { k: 'pick'; q: string; opts: string[]; a: number; why: string; t?: 'b' | 'a' }
  | { k: 'order'; q: string; items: string[]; why: string; t?: 'b' | 'a' } // items는 정답 순서, 화면에선 섞어서 보여줌
  | { k: 'sort'; q: string; bins: [string, string]; items: [string, 0 | 1][]; why: string; t?: 'b' | 'a' }
  | { k: 'num'; q: string; a: number; unit: string; why: string; t?: 'b' | 'a' }
  | { k: 'write'; q: string; keys: string[]; sample: string; why: string; t?: 'b' | 'a' }

export type LessonDef = {
  id: string
  title: string
  core?: string[] // 공통 핵심 (2~4줄)
  basic?: string // Basic 쉬운 예시
  adv?: string // Advanced 더 깊이
  qs?: Q[]
  note?: string // 내 노트에 남는 한 줄
}
export type ChapterDef = { id: string; title: string; lessons: LessonDef[] }
export type BuildingDef = { id: string; topic: string; goal: string; chapters: ChapterDef[] }

const L = (id: string, title: string): LessonDef => ({ id, title })
const outline = (pre: string, chapters: [string, string[]][]): ChapterDef[] =>
  chapters.map(([title, ls], ci) => ({ id: `${pre}${ci + 1}`, title, lessons: ls.map((t, li) => L(`${pre}${ci + 1}_${li + 1}`, t)) }))

export const isReady = (l: LessonDef) => !!l.qs?.length
export const qsFor = (l: LessonDef, track: Track) => (l.qs ?? []).filter((q) => !q.t || (track === 'basic' ? q.t === 'b' : q.t === 'a'))

